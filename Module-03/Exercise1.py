# 1. List of Integers
year_levels = [1, 2, 3, 4, 5]

# 2. List of Strings
students_name = ["Justine Gicanal", "Conrad Salayog", "Renzo Agustin", "Daryll Sabanal", "Vhon Aguilar"]

# 3. Mixed-type List
student_profile = ["Justine Jake Gicanal", "2025-03149-MN-0", 1.25, True]

# 4. Another List of Integers
course_codes = [201, 1012, 3006, 2020, 2032]

# DISPLAY CONTENTS
print("Year Levels:", year_levels)
print("Students Name:", students_name)
print("Students Profile:", student_profile)
print("Course Codes:", course_codes)

# DISPLAY LENGTHS
print("Length of Year Levels:", len(year_levels))
print("Length of Students Name:", len(students_name))
print("Length of Students Profile:", len(student_profile))
print("Length of Course Codes:", len(course_codes))

# INDEXING
print("\nFirst element of student_profile:", student_profile[0])
print("Last element of student_profile:", student_profile[-1])

# MEMBERSHIP TEST
print("\nIs 201 in course_codes?", 201 in course_codes)




